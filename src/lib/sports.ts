export function sportById(id: string) {
  return sportPages.find((sport) => sport.id === id);
}

export function listingById(sportId: string, listingId: string) {
  const sport = sportById(sportId);
  const listing = sport?.listings.find((item) => item.id === listingId);
  if (!sport || !listing) return null;
  return { sport, listing };
}
