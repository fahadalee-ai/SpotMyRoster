const listingPhotos = import.meta.glob("../assets/images/sports/*.jpg", {
  eager: true,
  import: "default",
}) as Record<string, string>;

function photo(file: string) {
  const match = Object.entries(listingPhotos).find(([path]) => path.endsWith(`/${file}.jpg`));
  if (!match) throw new Error(`Missing listing photo: ${file}`);
  return match[1];
}

